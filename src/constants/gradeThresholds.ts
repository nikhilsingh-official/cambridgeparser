/**
 * One session's published component thresholds, in RAW MARKS:
 *
 *     [maxMark, A, B, C, D, E, F, G]
 *
 * `null` where the paper's tier cannot award that grade - Core-tier IGCSE
 * components show an en dash for A and B in the source documents, and a zero
 * there would read as "grade A at nought marks".
 */
export type SessionThresholds = readonly [
  number,
  number | null, number | null, number | null, number | null,
  number | null, number | null, number | null,
];


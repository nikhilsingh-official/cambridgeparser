// ==========================================================================
//
// Cambridge grade thresholds, two ways. The source extraction tool is
// archived outside this repository; review any replacement dataset manually.
//
//   SESSION_THRESHOLDS - what was published for one exact paper.
//   PAPER_THRESHOLDS   - the mean per (syllabus, paper), for everything else.
//
// Prefer the session row. It is not an estimate of the boundary, it IS the
// boundary, and for a past paper we always know which session it came from.
//
// Built from 405 published grade-threshold documents (4612 component
// rows) scraped from PapaCambridge, which mirrors Cambridge's own files.
//
// EACH NUMBER IS A MEAN OF threshold/max_mark ACROSS SESSIONS AND VARIANTS.
// Real thresholds move between sessions because papers differ in difficulty;
// `sd` is carried so the size of that spread is visible at the point of use.
// See scripts/gt/build.py for what the averaging costs.
//
// There is no A* here, by construction: the source documents state that
// "Grade A* does not exist at the level of an individual component".
// ==========================================================================

export interface ThresholdStat {
  /** Mean of threshold / max_mark. */
  mean: number;
  /** Population standard deviation of the same, across sessions. */
  sd: number;
  min: number;
  max: number;
  /** Component rows behind the mean. */
  n: number;
}

export interface PaperThresholds {
  code: string;
  paper: number;
  qualification: string;
  /** Modal maximum raw mark for this paper. */
  maxMark: number;
  /** [earliest, latest] session year behind these means. */
  years: [number, number];
  /**
   * Set only when this describes ONE session - 'June 2024'. Absent on the
   * averaged rows, so its presence is what tells a caller whether it is
   * holding a real boundary or a mean of several.
   */
  session?: string;
  /** Highest grade first. Core-tier papers legitimately lack A and B. */
  grades: Partial<Record<'A' | 'B' | 'C' | 'D' | 'E' | 'F' | 'G', ThresholdStat>>;
}

